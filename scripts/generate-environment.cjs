const fs = require('node:fs');
const path = require('node:path');

const projectRoot = path.resolve(__dirname, '..');
const localEnvPath = path.join(projectRoot, '.env.local');
const outputPath = path.join(
  projectRoot,
  'src',
  'environments',
  'environment.generated.ts',
);

function readLocalApiKey() {
  if (!fs.existsSync(localEnvPath)) return '';

  const match = fs
    .readFileSync(localEnvPath, 'utf8')
    .match(/^TMDB_API_KEY\s*=\s*(.+)$/m);

  return match ? match[1].trim().replace(/^['"]|['"]$/g, '') : '';
}

const tmdbApiKey = (process.env.TMDB_API_KEY || readLocalApiKey()).trim();
const generatedSource = `// Generated by scripts/generate-environment.cjs. Do not commit.\nexport const environment = {\n  tmdbApiKey: ${JSON.stringify(tmdbApiKey)},\n};\n`;

fs.mkdirSync(path.dirname(outputPath), { recursive: true });
fs.writeFileSync(outputPath, generatedSource, 'utf8');

if (!tmdbApiKey) {
  console.warn(
    'TMDB_API_KEY is not configured. Copy .env.example to .env.local and add your key.',
  );
}
